function readInitialLanguage() {
  if (typeof window === 'undefined') {
    return DEFAULT_LANGUAGE;
  }
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return messages[stored] ? stored : DEFAULT_LANGUAGE;
}

export const currentLanguage = ref(readInitialLanguage());
export const isEnglish = computed(() => currentLanguage.value === 'en');

export const languageOptions = [
  { label: messages['zh-CN']['settings.language.zh'], value: 'zh-CN' },
  { label: messages.en['settings.language.en'], value: 'en' },
];

export function setLanguage(language) {
  currentLanguage.value = messages[language] ? language : DEFAULT_LANGUAGE;
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, currentLanguage.value);
  }
}

export function t(key) {
  return messages[currentLanguage.value]?.[key] || messages[DEFAULT_LANGUAGE][key] || key;
}
